import { buildClientEnv, type ClientEnv } from '@drivx/firebase-client';

/**
 * Expo only inlines environment variables prefixed with EXPO_PUBLIC_, so the
 * plain names used in .env.example are read through that prefix here.
 */
export function mobileEnv(): ClientEnv {
  return buildClientEnv({
    EXPO_PUBLIC_FIREBASE_API_KEY: process.env.EXPO_PUBLIC_FIREBASE_API_KEY,
    EXPO_PUBLIC_FIREBASE_PROJECT_ID: process.env.EXPO_PUBLIC_FIREBASE_PROJECT_ID,
    EXPO_PUBLIC_FIREBASE_APP_ID: process.env.EXPO_PUBLIC_FIREBASE_APP_ID,
    EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN: process.env.EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN,
    EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET: process.env.EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET,
    EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: process.env.EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID,
    EXPO_PUBLIC_FIREBASE_DATABASE_URL: process.env.EXPO_PUBLIC_FIREBASE_DATABASE_URL,
    EXPO_PUBLIC_FIREBASE_EMULATOR: process.env.EXPO_PUBLIC_FIREBASE_EMULATOR,
    EXPO_PUBLIC_FIREBASE_EMULATOR_HOST: process.env.EXPO_PUBLIC_FIREBASE_EMULATOR_HOST,
    EXPO_PUBLIC_FIRESTORE_EMULATOR_PORT: process.env.EXPO_PUBLIC_FIRESTORE_EMULATOR_PORT,
    EXPO_PUBLIC_RTDB_EMULATOR_PORT: process.env.EXPO_PUBLIC_RTDB_EMULATOR_PORT,
    EXPO_PUBLIC_AUTH_EMULATOR_PORT: process.env.EXPO_PUBLIC_AUTH_EMULATOR_PORT,
    EXPO_PUBLIC_FUNCTIONS_EMULATOR_PORT: process.env.EXPO_PUBLIC_FUNCTIONS_EMULATOR_PORT,
    EXPO_PUBLIC_STORAGE_EMULATOR_PORT: process.env.EXPO_PUBLIC_STORAGE_EMULATOR_PORT,
    EXPO_PUBLIC_FIREBASE_FUNCTIONS_REGION: process.env.EXPO_PUBLIC_FIREBASE_FUNCTIONS_REGION,
    EXPO_PUBLIC_FUNCTIONS_BASE_URL: process.env.EXPO_PUBLIC_FUNCTIONS_BASE_URL,
    // A browser-restricted Maps JavaScript key is public by design. Restrict it
    // to the DrivX web domains and enable Maps JavaScript API in Google Cloud.
    EXPO_PUBLIC_GOOGLE_MAPS_WEB_API_KEY: process.env.EXPO_PUBLIC_GOOGLE_MAPS_WEB_API_KEY,
  });
}
